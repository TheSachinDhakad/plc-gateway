VALUE_TYPE_CODES = {"null": 0, "bool": 1, "int": 2, "float": 3, "str": 4, "array": 5}
VALUE_TYPE_NAMES = {v: k for k, v in VALUE_TYPE_CODES.items()}
_PARTITION_RE = re.compile(r"^p\d{6,8}$")
PARTITIONED_TABLES = {"plc_tag_history": "gateway_ts", "plc_events": "event_ts"}
_INT64 = (-(2**63), 2**63 - 1)


def value_columns(value: Any, value_type: str) -> tuple[Any, Any, Any, Any, Any]:
    """Map a Python value to (value_bool, value_int, value_float, value_str, value_json)."""
    if value is None:
        return None, None, None, None, None
    if value_type == "bool":
        return int(bool(value)), None, None, None, None
    if value_type == "int":
        if _INT64[0] <= value <= _INT64[1]:
            return None, int(value), None, None, None
        return None, None, None, str(value), None      # ULINT/LWORD above int64: lossless as text
    if value_type == "float":
        if math.isfinite(value):
            return None, None, float(value), None, None
        return None, None, None, repr(float(value)), None   # nan / inf / -inf
    if value_type == "str":
        return None, None, None, str(value)[:1024], None
    return None, None, None, None, json.dumps(_json_safe(value))


def value_from_row(row: dict[str, Any]) -> Any:
    vt = VALUE_TYPE_NAMES.get(int(row["value_type"]), "null")
    if vt == "bool":
        return bool(row["value_bool"]) if row["value_bool"] is not None else None
    if vt == "int":
        if row["value_int"] is not None:
            return int(row["value_int"])
        return int(row["value_str"]) if row.get("value_str") is not None else None
    if vt == "float":
        if row["value_float"] is not None:
            return float(row["value_float"])
        return row.get("value_str")    # 'nan' / 'inf' rendered as text in the API
    if vt == "str":
        return row["value_str"]
    if vt == "array":
        raw = row["value_json"]
        return json.loads(raw) if isinstance(raw, str | bytes) else raw
    return None


def _json(value: Any) -> str | None:
    return None if value is None else json.dumps(_json_safe(value), default=str)


def _tag_hash(tag: Any) -> str:
    return hashlib.sha256(tag.model_dump_json().encode()).hexdigest()


def partition_name(day: date, monthly: bool = False) -> str:
    return f"p{day:%Y%m}" if monthly else f"p{day:%Y%m%d}"


class Repository:
    def __init__(self, client: MySQLClient, gateway_id: str) -> None:
        self.db = client
        self.gateway_id = gateway_id
        self.tag_pks: dict[tuple[str, str], int] = {}
        self.device_pks: dict[str, int] = {}

    @property
    def registry_ready(self) -> bool:
        return bool(self.device_pks)

    # ================================================================== registry
    async def sync_registry(self, config: GatewayConfig) -> None:
        """Upsert plants/devices/tags from YAML and load the pk maps (idempotent)."""
        async with self.db.transaction() as cur:
            for plant in config.plants:
                await cur.execute(
                    "INSERT INTO plants (plant_id, name, enabled) VALUES (%s, %s, %s) "
                    "ON DUPLICATE KEY UPDATE name = VALUES(name), enabled = VALUES(enabled)",
                    (plant.plant_id, plant.name, int(plant.enabled)))
                await cur.execute("SELECT plant_pk FROM plants WHERE plant_id = %s", (plant.plant_id,))
                (plant_pk,) = await cur.fetchone()
                for device in plant.devices:
                    conn = device.connection
                    endpoint = getattr(conn, "host", None) or getattr(conn, "path", None) or getattr(
                        conn, "endpoint", None) or getattr(conn, "serial_port", None) or getattr(conn, "server_progid",
                                                                                                None)
                    await cur.execute(
                        "INSERT INTO plc_devices (plant_pk, device_id, name, driver, enabled, write_enabled, endpoint) "
                        "VALUES (%s, %s, %s, %s, %s, %s, %s) ON DUPLICATE KEY UPDATE plant_pk = VALUES(plant_pk), "
                        "name = VALUES(name), driver = VALUES(driver), enabled = VALUES(enabled), "
                        "write_enabled = VALUES(write_enabled), endpoint = VALUES(endpoint)",
                        (plant_pk, device.device_id, device.name, str(device.driver), int(device.enabled),
                         int(device.write_enabled), str(endpoint)[:255] if endpoint else None))
                    await cur.execute("SELECT device_pk FROM plc_devices WHERE device_id = %s", (device.device_id,))
                    (device_pk,) = await cur.fetchone()
                    rows = [
                        (device_pk, t.tag_id, t.name, t.description, t.group, t.address, t.data_type.value,
                         t.array_length, t.poll_interval_ms, t.logging_mode.value, t.engineering_unit,
                         t.access.value, int(t.enabled), _tag_hash(t))
                        for t in config.tags.get(device.device_id, [])
                    ]
                    if rows:
                        await cur.executemany(
                            "INSERT INTO plc_tags (device_pk, tag_id, name, description, tag_group, address, "
                            "data_type, array_length, poll_interval_ms, logging_mode, engineering_unit, "
                            "access_mode, enabled, config_hash) "
                            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) "
                            "ON DUPLICATE KEY UPDATE name = VALUES(name), description = VALUES(description), "
                            "tag_group = VALUES(tag_group), address = VALUES(address), data_type = VALUES(data_type), "
                            "array_length = VALUES(array_length), poll_interval_ms = VALUES(poll_interval_ms), "
                            "logging_mode = VALUES(logging_mode), engineering_unit = VALUES(engineering_unit), "
                            "access_mode = VALUES(access_mode), enabled = VALUES(enabled), "
                            "config_hash = VALUES(config_hash)", rows)
                    configured = {t.tag_id for t in config.tags.get(device.device_id, [])}
                    await cur.execute("SELECT tag_id FROM plc_tags WHERE device_pk = %s AND enabled = 1", (device_pk,))
                    for (tag_id,) in await cur.fetchall():
                        if tag_id not in configured:   # removed from YAML: keep history, mark disabled
                            await cur.execute("UPDATE plc_tags SET enabled = 0 WHERE device_pk = %s AND tag_id = %s",
                                              (device_pk, tag_id))
        await self.load_registry()

    async def load_registry(self) -> None:
        rows = await self.db.fetch_all(
            "SELECT d.device_id, d.device_pk, t.tag_id, t.tag_pk FROM plc_devices d "
            "LEFT JOIN plc_tags t ON t.device_pk = d.device_pk")
        device_pks: dict[str, int] = {}
        tag_pks: dict[tuple[str, str], int] = {}
        for r in rows:
            device_pks[r["device_id"]] = int(r["device_pk"])
            if r["tag_id"] is not None:
                tag_pks[(r["device_id"], r["tag_id"])] = int(r["tag_pk"])
        self.device_pks, self.tag_pks = device_pks, tag_pks

    # ================================================================== data writes
    def _history_row(self, tag_pk: int, r: TagReading) -> tuple[Any, ...]:
        vb, vi, vf, vs, vj = value_columns(r.value, r.value_type)
        return (tag_pk, to_mysql(r.gateway_timestamp), r.reading_uid.bytes, to_mysql(r.source_timestamp),
                1 if r.timestamp_origin == "device" else 0, VALUE_TYPE_CODES[r.value_type], vb, vi, vf, vs, vj,
                QUALITY_CODES[r.quality], r.error_code)

    async def write_batch(self, readings: Sequence[TagReading], events: Sequence[TagEvent]) -> tuple[int, int, int]:
        """Insert history + upsert latest + insert events in ONE transaction.

        Returns (history_rows, event_rows, skipped_unknown). Idempotent on replay.
        """
        history: list[tuple[Any, ...]] = []
        latest: dict[int, tuple[Any, ...]] = {}
        latest_ts: dict[int, datetime] = {}
        skipped = 0
        for r in readings:
            tag_pk = self.tag_pks.get((r.device_id, r.tag_id))
            if tag_pk is None:
                skipped += 1
                continue
            row = self._history_row(tag_pk, r)
            if r.logging_mode != "none":
                history.append(row)
            if tag_pk not in latest_ts or r.gateway_timestamp >= latest_ts[tag_pk]:
                latest_ts[tag_pk] = r.gateway_timestamp
                latest[tag_pk] = (row[0], row[1], *row[3:])
        event_rows = []
        for e in events:
            device_pk = self.device_pks.get(e.device_id)
            if device_pk is None:
                skipped += 1
                continue
            tag_pk = self.tag_pks.get((e.device_id, e.tag_id)) if e.tag_id else None
            event_rows.append((to_mysql(e.event_timestamp), e.event_uid.bytes, device_pk, tag_pk, e.event_type.value,
                               _json(e.previous_value), _json(e.new_value), e.previous_quality, e.new_quality,
                               e.threshold if e.threshold is None or math.isfinite(e.threshold) else None,
                               (e.message or "")[:512] or None))
        async with self.db.transaction() as cur:
            if history:
                await cur.executemany(
                    "INSERT INTO plc_tag_history (tag_pk, gateway_ts, reading_uid, source_ts, ts_origin, value_type, "
                    "value_bool, value_int, value_float, value_str, value_json, quality, error_code) "
                    "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) "
                    "ON DUPLICATE KEY UPDATE tag_pk = tag_pk", history)
            if latest:
                # only move forward in time (spool replay of old rows must not regress latest)
                cols = ("source_ts", "ts_origin", "value_type", "value_bool", "value_int", "value_float",
                        "value_str", "value_json", "quality", "error_code")
                updates = ", ".join(f"{c} = IF(VALUES(gateway_ts) >= gateway_ts, VALUES({c}), {c})" for c in cols)
                await cur.executemany(
                    "INSERT INTO plc_tag_latest (tag_pk, gateway_ts, source_ts, ts_origin, value_type, value_bool, "  # noqa: S608
                    "value_int, value_float, value_str, value_json, quality, error_code) "
                    "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) "
                    f"ON DUPLICATE KEY UPDATE {updates}, "
                    "gateway_ts = GREATEST(gateway_ts, VALUES(gateway_ts))",
                    list(latest.values()))
            if event_rows:
                await cur.executemany(
                    "INSERT INTO plc_events (event_ts, event_uid, device_pk, tag_pk, event_type, previous_value, "
                    "new_value, previous_quality, new_quality, threshold, message) "
                    "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) ON DUPLICATE KEY UPDATE event_uid = event_uid",
                    event_rows)
        return len(history), len(event_rows), skipped

    # ================================================================== write commands / audit
    async def get_write_command(self, request_id: str) -> Any:
        from core.write_manager import WriteCommand

        row = await self.db.fetch_one("SELECT * FROM plc_write_commands WHERE request_id = %s", (request_id,))
        if row is None:
            return None
        return WriteCommand(
            request_id=row["request_id"], plant_id=row["plant_id"], device_id=row["device_id"], tag_id=row["tag_id"],
            principal=row["principal"], requested_value=_loads(row["requested_value"]), reason=row["reason"],
            status=WriteStatus(row["status"]), readback_value=_loads(row["readback_value"]),
            error_code=row["error_code"], error_message=row["error_message"],
            requested_at=from_mysql(row["requested_at"]) or utc_now(), completed_at=from_mysql(row["completed_at"]),
            duration_ms=row["duration_ms"])

    async def insert_write_command(self, cmd: Any) -> None:
        await self.db.execute(
            "INSERT INTO plc_write_commands (request_id, plant_id, device_id, tag_id, principal, requested_value, "
            "reason, status, error_code, error_message, requested_at, completed_at) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)",
            (cmd.request_id, cmd.plant_id, cmd.device_id, cmd.tag_id, cmd.principal, _json(cmd.requested_value),
             (cmd.reason or "")[:512] or None, cmd.status.value, cmd.error_code,
             (cmd.error_message or "")[:1024] or None,
             to_mysql(cmd.requested_at), to_mysql(cmd.completed_at) if cmd.completed_at else None))

    async def update_write_command(self, cmd: Any) -> None:
        await self.db.execute(
            "UPDATE plc_write_commands SET status = %s, readback_value = %s, error_code = %s, error_message = %s, "
            "completed_at = %s, duration_ms = %s WHERE request_id = %s",
            (cmd.status.value, _json(cmd.readback_value), cmd.error_code, (cmd.error_message or "")[:1024] or None,
             to_mysql(cmd.completed_at) if cmd.completed_at else None, cmd.duration_ms, cmd.request_id))

    async def list_write_commands(self, *, device_id: str | None, limit: int, offset: int) -> list[dict[str, Any]]:
        sql = "SELECT * FROM plc_write_commands"
        args: list[Any] = []
        if device_id:
            sql += " WHERE device_id = %s"
            args.append(device_id)
        sql += " ORDER BY requested_at DESC LIMIT %s OFFSET %s"
        args += [limit, offset]
        return await self.db.fetch_all(sql, args)

    async def insert_audit(self, *, action: str, principal: str | None, result: str, device_id: str | None = None,
                           tag_id: str | None = None, request_id: str | None = None,
                           detail: dict[str, Any] | None = None) -> None:
        await self.db.execute(
            "INSERT INTO audit_logs (ts, gateway_id, action, principal, result, device_id, tag_id, request_id, detail) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)",
            (to_mysql(utc_now()), self.gateway_id, action, principal, result, device_id, tag_id, request_id,
             _json(detail)))

    async def insert_health(self, rows: Sequence[dict[str, Any]]) -> None:
        if not rows:
            return
        cols = ("snapshot_ts", "gateway_id", "device_id", "status", "connected", "reads_ok", "reads_failed",
                "reconnects", "poll_p95_ms", "queue_size", "spool_rows", "dropped_total", "db_insert_p95_ms",
                "cpu_percent", "rss_mb", "detail")
        values = [tuple(_json(r.get(c)) if c == "detail" else r.get(c) for c in cols) for r in rows]
        async with self.db.transaction() as cur:
            await cur.executemany(
                f"INSERT INTO gateway_health ({', '.join(cols)}) "  # noqa: S608 - constant column names
                f"VALUES ({', '.join(['%s'] * len(cols))}) "
                "ON DUPLICATE KEY UPDATE status = VALUES(status)", values)

    # ================================================================== queries
    async def latest(self, *, device_id: str | None = None, tag_id: str | None = None) -> list[dict[str, Any]]:
        sql = ("SELECT p.plant_id, d.device_id, d.name AS device_name, t.tag_id, t.name AS tag_name, t.data_type, "
               "t.engineering_unit, l.* FROM plc_tag_latest l JOIN plc_tags t ON t.tag_pk = l.tag_pk "
               "JOIN plc_devices d ON d.device_pk = t.device_pk JOIN plants p ON p.plant_pk = d.plant_pk WHERE 1=1")
        args: list[Any] = []
        if device_id:
            sql += " AND d.device_id = %s"
            args.append(device_id)
        if tag_id:
            sql += " AND t.tag_id = %s"
            args.append(tag_id)
        rows = await self.db.fetch_all(sql + " ORDER BY d.device_id, t.tag_id", args)
        return [_reading_row(r) for r in rows]

    async def history(self, *, start: datetime, end: datetime, device_id: str | None, tag_id: str | None,
                      limit: int, offset: int) -> tuple[list[dict[str, Any]], bool]:
        sql = ("SELECT d.device_id, t.tag_id, t.data_type, t.engineering_unit, h.* FROM plc_tag_history h "
               "JOIN plc_tags t ON t.tag_pk = h.tag_pk JOIN plc_devices d ON d.device_pk = t.device_pk "
               "WHERE h.gateway_ts >= %s AND h.gateway_ts < %s")
        args: list[Any] = [to_mysql(start), to_mysql(end)]
        if device_id:
            sql += " AND d.device_id = %s"
            args.append(device_id)
        if tag_id:
            sql += " AND t.tag_id = %s"
            args.append(tag_id)
        sql += " ORDER BY h.gateway_ts, h.tag_pk, h.reading_uid LIMIT %s OFFSET %s"
        args += [limit + 1, offset]
        rows = await self.db.fetch_all(sql, args)
        return [_reading_row(r) for r in rows[:limit]], len(rows) > limit

    async def events(self, *, start: datetime, end: datetime, device_id: str | None, tag_id: str | None,
                     event_type: str | None, limit: int, offset: int) -> tuple[list[dict[str, Any]], bool]:
        sql = ("SELECT e.event_ts, e.event_uid, d.device_id, t.tag_id, e.event_type, e.previous_value, e.new_value, "
               "e.previous_quality, e.new_quality, e.threshold, e.message FROM plc_events e "
               "JOIN plc_devices d ON d.device_pk = e.device_pk LEFT JOIN plc_tags t ON t.tag_pk = e.tag_pk "
               "WHERE e.event_ts >= %s AND e.event_ts < %s")
        args: list[Any] = [to_mysql(start), to_mysql(end)]
        if device_id:
            sql += " AND d.device_id = %s"
            args.append(device_id)
        if tag_id:
            sql += " AND t.tag_id = %s"
            args.append(tag_id)
        if event_type:
            sql += " AND e.event_type = %s"
            args.append(event_type)
        sql += " ORDER BY e.event_ts DESC LIMIT %s OFFSET %s"
        args += [limit + 1, offset]
        rows = await self.db.fetch_all(sql, args)
        out = [{
            "event_uid": str(uuid.UUID(bytes=bytes(r["event_uid"]))), "event_timestamp": from_mysql(r["event_ts"]),
            "device_id": r["device_id"], "tag_id": r["tag_id"], "event_type": r["event_type"],
            "previous_value": _loads(r["previous_value"]), "new_value": _loads(r["new_value"]),
            "previous_quality": r["previous_quality"], "new_quality": r["new_quality"],
            "threshold": r["threshold"], "message": r["message"]} for r in rows[:limit]]
        return out, len(rows) > limit

    # ================================================================== partitions / retention
    async def list_partitions(self, table: str) -> list[dict[str, Any]]:
        _check_table(table)
        return await self.db.fetch_all(
            "SELECT PARTITION_NAME AS name, PARTITION_DESCRIPTION AS bound, TABLE_ROWS AS row_estimate, "
            "DATA_LENGTH + INDEX_LENGTH AS bytes FROM information_schema.PARTITIONS "
            "WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = %s AND PARTITION_NAME IS NOT NULL "
            "ORDER BY PARTITION_ORDINAL_POSITION", (table,))

    @staticmethod
    def _bound(p: dict[str, Any]) -> date | None:
        bound = str(p.get("bound") or "").strip("'")
        try:
            return date.fromisoformat(bound[:10])
        except ValueError:
            return None

    async def ensure_partitions(self, table: str, *, start: date, until: date, monthly: bool) -> list[str]:
        """Split ``p_future`` so dated partitions cover [start, until]. Returns created partition names.

        The first dated partition also holds anything older than ``start`` (ranges are contiguous).
        """
        _check_table(table)
        parts = await self.list_partitions(table)
        if not any(p["name"] == "p_future" for p in parts):
            raise DatabaseError(f"{table} has no p_future partition; was the schema applied?")
        bounds = [b for p in parts if _PARTITION_RE.match(p["name"] or "") and (b := self._bound(p))]
        cursor = start.replace(day=1) if monthly else start
        if bounds:
            cursor = max(cursor, max(bounds))
        new: list[tuple[str, date]] = []
        while cursor <= until:
            nxt = (cursor.replace(day=28) + timedelta(days=4)).replace(day=1) if monthly else cursor + timedelta(days=1)
            new.append((partition_name(cursor, monthly), nxt))
            cursor = nxt
        if not new:
            return []
        for name, _ in new:
            if not _PARTITION_RE.match(name):
                raise DatabaseError(f"refusing unexpected partition name {name}")
        spec = ", ".join(f"PARTITION {n} VALUES LESS THAN ('{b.isoformat()}')" for n, b in new)
        await self.db.execute(
            f"ALTER TABLE {table} REORGANIZE PARTITION p_future INTO "
            f"({spec}, PARTITION p_future VALUES LESS THAN (MAXVALUE))")
        return [n for n, _ in new]

    async def expired_partitions(self, table: str, cutoff: date) -> list[str]:
        """Partitions whose upper bound is <= cutoff (all rows older than cutoff)."""
        out = []
        for p in await self.list_partitions(table):
            name = p["name"]
            if not _PARTITION_RE.match(name or ""):
                continue
            upper = self._bound(p)
            if upper is not None and upper <= cutoff:
                out.append(name)
        return out

    async def export_partition(self, table: str, name: str, target_dir: Path) -> Path:
        _check_table(table)
        if not _PARTITION_RE.match(name):
            raise DatabaseError(f"invalid partition name {name}")
        path = target_dir / f"{table}_{name}.csv.gz"
        # table/partition names are validated above (never user input)
        rows = await self.db.fetch_all(f"SELECT * FROM {table} PARTITION ({name})")  # noqa: S608
        await asyncio.to_thread(_write_csv_gz, path, rows)
        return path

    async def drop_partition(self, table: str, name: str) -> None:
        _check_table(table)
        if not _PARTITION_RE.match(name):
            raise DatabaseError(f"invalid partition name {name}")
        await self.db.execute(f"ALTER TABLE {table} DROP PARTITION {name}")

    async def delete_older_than(self, table: str, column: str, cutoff: datetime, chunk: int = 10_000) -> int:
        allowed = {("gateway_health", "snapshot_ts"), ("audit_logs", "ts"), ("plc_write_commands", "requested_at")}
        if (table, column) not in allowed:
            raise DatabaseError(f"retention delete not allowed for {table}.{column}")
        total = 0
        while True:
            n = await self.db.execute(f"DELETE FROM {table} WHERE {column} < %s LIMIT %s",  # noqa: S608 - allowlisted
                                      (to_mysql(cutoff), chunk))
            total += n
            if n < chunk:
                return total


def _write_csv_gz(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt", newline="", encoding="utf-8") as fh:
        writer = None
        for r in rows:
            if writer is None:
                writer = csv.DictWriter(fh, fieldnames=list(r.keys()))
                writer.writeheader()
            writer.writerow({k: (v.hex() if isinstance(v, bytes | bytearray) else v) for k, v in r.items()})


def _check_table(table: str) -> None:
    if table not in PARTITIONED_TABLES:
        raise DatabaseError(f"table {table} is not a managed partitioned table")


def _loads(value: Any) -> Any:
    if value is None:
        return None
    if isinstance(value, bytes | bytearray):
        value = value.decode()
    if isinstance(value, str):
        return json.loads(value)
    return value


def _reading_row(r: dict[str, Any]) -> dict[str, Any]:
    quality = QUALITY_FROM_CODE.get(int(r["quality"]), Quality.BAD)
    out = {
        "device_id": r["device_id"],
        "tag_id": r["tag_id"],
        "value": value_from_row(r),
        "value_type": VALUE_TYPE_NAMES.get(int(r["value_type"]), "null"),
        "data_type": r.get("data_type"),
        "quality": quality.value,
        "gateway_timestamp": from_mysql(r["gateway_ts"]),
        "source_timestamp": from_mysql(r.get("source_ts")),
        "timestamp_origin": "device" if r.get("ts_origin") else "gateway_read",
        "engineering_unit": r.get("engineering_unit"),
        "error_code": r.get("error_code"),
    }
    for key in ("plant_id", "device_name", "tag_name"):
        if key in r:
            out[key] = r[key]
    if "reading_uid" in r and r["reading_uid"] is not None:
        out["reading_uid"] = str(uuid.UUID(bytes=bytes(r["reading_uid"])))
    return out
